#!/usr/bin/env bash
# Generate local demo secrets. Idempotent: existing files are kept unless
# --force is passed.
#
#   scripts/gen-secrets.sh
#   scripts/gen-secrets.sh --force   # rotate; existing Iggy data will reject
#                                    # the new root password until `make reset`
#
# Writes:
#   .env                         0600, non-secret Compose settings
#   secrets/iggy_root_password   0600, Iggy root password
#   secrets/iggy_cluster_psk     0600, HA cluster pre-shared key (experimental)
#
# Never commit .env or secrets/. Both are in .gitignore and .dockerignore.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SECRETS_DIR="${ROOT}/secrets"
ENV_FILE="${ROOT}/.env"
FORCE=0

case "${1:-}" in
    --force)
        FORCE=1
        ;;
    "")
        ;;
    -h|--help)
        sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
        exit 0
        ;;
    *)
        echo "unknown argument: $1 (use --force)" >&2
        exit 2
        ;;
esac

umask 077

gen_hex() {
    local bytes="$1"
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex "${bytes}"
    else
        od -An -N"${bytes}" -tx1 /dev/urandom | tr -d ' \n'
    fi
}

write_secret() {
    local path="$1"
    local value="$2"
    if [ -s "${path}" ] && [ "${FORCE}" -eq 0 ]; then
        chmod 600 "${path}"
        echo "keeping ${path#"${ROOT}/"}"
        return
    fi
    local tmp
    tmp="$(mktemp "${path}.XXXXXX")"
    printf '%s\n' "${value}" >"${tmp}"
    chmod 600 "${tmp}"
    mv "${tmp}" "${path}"
    echo "wrote   ${path#"${ROOT}/"}"
}

mkdir -p "${SECRETS_DIR}"
chmod 700 "${SECRETS_DIR}"

write_secret "${SECRETS_DIR}/iggy_root_password" "$(gen_hex 24)"
write_secret "${SECRETS_DIR}/iggy_cluster_psk" "$(gen_hex 32)"

if [ ! -f "${ENV_FILE}" ] || [ "${FORCE}" -eq 1 ]; then
    cat >"${ENV_FILE}" <<'EOF'
# Generated by scripts/gen-secrets.sh. Do not commit.
# The Iggy root password lives in secrets/iggy_root_password, not here.
COMPOSE_PROJECT_NAME=whippet
IGGY_ROOT_USERNAME=whippet
WHIPPET_BUILD=local

# Optional demo overrides:
# WHIPPET_SIM_RATE=50
# WHIPPET_SIM_SCENARIO=calm_open
# WHIPPET_SNAPSHOT_EVERY=1000
# IGGY_LOGGING_LEVEL=info
# GRAFANA_ADMIN_USER=admin
# GRAFANA_ADMIN_PASSWORD=change-me
EOF
    chmod 600 "${ENV_FILE}"
    echo "wrote   .env"
else
    chmod 600 "${ENV_FILE}"
    if ! grep -q '^IGGY_ROOT_USERNAME=' "${ENV_FILE}"; then
        printf '\nIGGY_ROOT_USERNAME=whippet\n' >>"${ENV_FILE}"
    fi
    echo "keeping .env"
fi

echo
echo "Iggy root user: $(grep -m1 '^IGGY_ROOT_USERNAME=' "${ENV_FILE}" | cut -d= -f2- || true)"
echo "Secrets are 0600 in ${SECRETS_DIR#"${ROOT}/"}/; .env is 0600."
